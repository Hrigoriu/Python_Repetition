# --- Список для виводу: (опис, значення) ---
results = [
    ("Оригінальний список",      words),
    ('" → ".join()',              arrow_chain),
    ('", ".join()',               comma_chain),
    ('"-".join()',                dash_chain),
    ('"".join()',                 no_space_chain),
]

# --- Вивід у рамці ---
label_width = max(len(label) for label, _ in results)
value_width = max(len(str(value)) for _, value in results)
width = label_width + value_width + 5

print("\n┌" + "─" * width + "┐")
print("│" + "  JOIN() — ВАРІАНТИ РОЗДІЛЬНИКА".center(width) + "│")
