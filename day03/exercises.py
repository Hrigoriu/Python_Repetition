#Практика №5

patient = "Ivan"
age = 42
diagnosis = "Acute sinusitis"
bmi = 25.678

# Один f-string з переносами рядків (\n) формує весь звіт одразу
report = f"Patient: {patient}\nAge: {age}\nDiagnosis: {diagnosis}\nBMI: {bmi:.1f}"

# --- Вивід у рамці ---
lines = report.split("\n")   # розбиваємо назад на окремі рядки для рамки
