import re


def analyze_medical_text(text: str) -> None:
    """Аналізує медичний текст: пробіли, довжина, слова, пошук ключових термінів."""

    # 1. Прибираємо зайві пробіли: strip() по краях + split()/join()
    #    автоматично схлопує кілька пробілів підряд в один
    cleaned = " ".join(text.split())

    # 2. Кількість символів — довжина вже ОЧИЩЕНОГО рядка
    char_count = len(cleaned)

    # 3. Кількість слів: токенізуємо через regex — розбиваємо на
    #    слова (\w+) і окремі знаки пунктуації ([^\w\s]) як окремі токени
    # tokens = re.findall(r"\w+|[^\w\s]", cleaned)
    # word_count = len(tokens)

    # 3. Кількість слів: токенізуємо через regex — розбиваємо на слова (\w+)
    words = re.findall(r"\w+", cleaned)
    word_count = len(words)

    # 4. Переводимо текст у нижній регістр (для пошуку без урахування регістру)
    lowered = cleaned.lower()

    # 5. Перевіряємо наявність ключових медичних термінів
    keywords = ["pain", "fever", "cough", "sinusitis"]
    found = [word for word in keywords if word in lowered]

    # 6.--- Вивід результату у рамці ---
    lines = [
        f"Characters: {char_count}",
        f"Words: {word_count}",
        "Found:",
    ]
    if found:
        lines += [f"  - {word}" for word in found]
    else:
        lines.append("  (none)")

    # 7. Заголовок
    title = "MEDICAL TEXT ANALYSIS"

    # 8. Розраховуємо ширину з урахуванням і title, і lines
    width = max(len(title), max(len(line) for line in lines)) + 4

    # 9. Виводимо рамку
    print("┌" + "─" * width + "┐")
    print("│" + title.center(width) + "│")
    print("├" + "─" * width + "┤")

    for line in lines:
        print("│" + line.ljust(width) + "│")

    print("└" + "─" * width + "┘")


# --- Приклад використання ---

analyze_medical_text(" Patient complains of fever and sinusitis. ")

