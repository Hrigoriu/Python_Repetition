# Функції форматування
# ══════════════════════════════════════════

def pad_text(text: str, width: int, align: str = "<") -> str:
    """Вирівнює текст з урахуванням ширини Unicode-символів."""

    text = str(text)

    text_width = wcswidth(text)

    # Якщо wcwidth не може визначити ширину
    if text_width < 0:
        text_width = len(text)

    spaces = max(0, width - text_width)

    if align == "^":
        left_spaces = spaces // 2
        right_spaces = spaces - left_spaces

        return (
            " " * left_spaces
            + text
            + " " * right_spaces
        )

    elif align == ">":
        return " " * spaces + text

    else:
        return text + " " * spaces


def make_separator(
    left: str = "├",
    middle: str = "┼",
    right: str = "┤",
) -> str:
    """Створює горизонтальну лінію таблиці."""

    return (
        left
        + "─" * (W_AGE + 2)
        + middle
        + "─" * (W_TEMP + 2)
        + middle
        + "─" * (W_COUGH + 2)
        + middle
        + "─" * (W_THROAT + 2)
        + middle
        + "─" * (W_RESULT + 2)
        + middle
        + "─" * (W_DESC + 2)
        + right
    )

