# Вивід таблиці
# ══════════════════════════════════════════

# Загальна ширина таблиці
TABLE_WIDTH = (
    W_AGE
    + W_TEMP
    + W_COUGH
    + W_THROAT
    + W_RESULT
    + W_DESC
    + 12
)

# Верхня рамка
print()
