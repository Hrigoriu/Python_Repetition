# Практика №4 — пошук
"""
Є:
patients = [
    "Ivan",
    "Olena",
    "Petro",
    "Hanna",
]

Знайди "Petro" за допомогою циклу.

Після знаходження:
Patient found
і припини цикл.
"""

patients = [
    "Ivan",
    "Olena",
    "Petro",
    "Hanna",
]

target = "Petro"  # кого шукаємо
steps = []  # список кроків для виводу в рамці
found = False  # прапорець: пацієнта ще не знайдено

# --- for/else: особливість Python ---
# else при for виконується ТІЛЬКИ якщо цикл завершився БЕЗ break
# якщо break спрацював — else пропускається
for patient in patients:
    if patient == target:
        steps.append(f"✅ {patient} ← знайдено!")
        found = True
        break  # зупиняємо цикл одразу
    else:
        steps.append(f"🔍 {patient} — не той, шукаємо далі...")
else:
    # цей блок виконається ТІЛЬКИ якщо break не спрацював
    steps.append(f"❌ Пацієнта '{target}' не знайдено у списку")

# --- Вивід у рамці ---
title = f"ПОШУК ПАЦІЄНТА: {target}"
width = max(len(title), max(len(s) for s in steps)) + 4

print("\n┌" + "─" * width + "┐")
print("│" + f"  {title}".center(width) + "│")
print("├" + "─" * width + "┤")
for step in steps:
    print("│  " + step.ljust(width - 2) + "│")
print("├" + "─" * width + "┤")

# Фінальний результат
result = "✅ Patient found" if found else "❌ Patient not found"
print("│  " + result.ljust(width - 2) + "│")
print("└" + "─" * width + "┘")

