for num in numbers:
    print("│  " + f"{num} % 2 = {num % 2}".ljust(width - 2) + "│")
print("├" + "─" * width + "┤")
print("│  " + f"Всього: {len(numbers)}".ljust(width - 2) + "│")
print("└" + "─" * width + "┘")

