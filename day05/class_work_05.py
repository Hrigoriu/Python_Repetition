# Варіант 2 — range() + if з оператором %:

# range(1, 21) генерує всі числа від 1 до 20
# % — оператор остачі від ділення (modulo)
# num % 2 == 0 → остача від ділення на 2 дорівнює 0 → число парне
numbers = [num for num in range(1, 21) if num % 2 == 0]

# --- Вивід у рамці ---
