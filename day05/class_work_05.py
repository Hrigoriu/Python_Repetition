if access:
    print("│  " + "✅ Access granted".ljust(width - 2) + "│")
else:
    print("│  " + "🔒 Access denied".ljust(width - 2) + "│")
    print("│  " + "Обліковий запис заблоковано!".ljust(width - 2) + "│")

