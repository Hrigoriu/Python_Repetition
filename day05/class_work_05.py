rows = []

for temp in temperatures:
    # continue — негайно переходить до НАСТУПНОЇ ітерації,
    # весь код ПІСЛЯ continue в цьому кроці — пропускається
    if temp < THRESHOLD:
        rows.append(f"⏭ {temp:.1f} °C  ← пропущено (< {THRESHOLD})")
        continue  # ← повертаємось на початок циклу

