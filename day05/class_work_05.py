# замість роботи з tuple (item[0], item[1]) — розпаковуємо одразу
print("Розпаковка tuple у дві змінні:")
for index, name in enumerate(patients, start=1):
    print(f"{index}. {name}")  # саме такий вивід вимагає завдання

# --- Вивід у рамці ---
rows = [f"{i}. {name}" for i, name in enumerate(patients, start=1)]
width = max(len(row) for row in rows) + 4

print("\n┌" + "─" * width + "┐")
print("│" + "  СПИСОК ПАЦІЄНТІВ".center(width) + "│")
print("├" + "─" * width + "┤")
for row in rows:
    print("│  " + row.ljust(width - 2) + "│")
